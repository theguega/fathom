/// The glyph cell for a character, or the cell for `?` when unmapped.
#[inline]
pub(crate) fn glyph_index(c: char) -> u32 {
    match c as u32 {
        c @ 0x20..=0x7F => c - 0x20,
        c @ 0xA0..=0xFF => c - 0xA0 + 96,
        _ => u32::from(b'?') - 0x20,
    }
}

/// Top-left atlas pixel of a glyph cell.
#[inline]
pub(crate) fn glyph_origin(index: u32) -> (u32, u32) {
    (index % COLS * GLYPH, index / COLS * GLYPH)
}

/// UV of the solid-white texel, which is what makes lines and filled polygons
/// share the textured pipeline instead of needing one of their own.
#[inline]
pub(crate) fn white_uv() -> glam::Vec2 {
    #[allow(clippy::cast_precision_loss)]
    glam::Vec2::new(
        (WHITE_TEXEL.0 as f32 + 0.5) / ATLAS as f32,
        (WHITE_TEXEL.1 as f32 + 0.5) / ATLAS as f32,
    )
}

/// Rasterize the whole atlas into RGBA8: white everywhere, alpha carrying glyph
/// coverage, plus the opaque white texel. Called once, at context creation.
pub(crate) fn bake_atlas() -> Vec<u8> {
    let mut px = vec![0u8; (ATLAS * ATLAS * 4) as usize];
    let mut set = |x: u32, y: u32, a: u8| {
        let i = ((y * ATLAS + x) * 4) as usize;
        if let Some(texel) = px.get_mut(i..i + 4) {
            texel.copy_from_slice(&[255, 255, 255, a]);
        }
    };

    for (index, rows) in GLYPHS.chunks_exact(GLYPH as usize).enumerate() {
        #[allow(clippy::cast_possible_truncation)]
        let (ox, oy) = glyph_origin(index as u32);
        for (dy, bits) in rows.iter().enumerate() {
            for dx in 0..GLYPH {
                if bits & (1 << dx) != 0 {
                    #[allow(clippy::cast_possible_truncation)]
                    set(ox + dx, oy + dy as u32, 255);
                }
            }
        }
    }

    for dy in 0..2 {
        for dx in 0..2 {
            set(WHITE_TEXEL.0 + dx, WHITE_TEXEL.1 + dy, 255);
        }
    }
    px
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_ascii_and_latin1_and_falls_back() {
        assert_eq!(glyph_index(' '), 0);
        assert_eq!(glyph_index('A'), 33);
        assert_eq!(glyph_index('\u{00A0}'), 96);
        assert_eq!(glyph_index('\u{00FF}'), 191);
        assert_eq!(glyph_index('\u{4E00}'), glyph_index('?'));
        assert_eq!(glyph_index('\n'), glyph_index('?'));
    }

    #[test]
    fn atlas_has_ink_where_it_should() {
        let px = bake_atlas();
        assert_eq!(px.len(), (ATLAS * ATLAS * 4) as usize);
        let alpha_at = |x: u32, y: u32| px[((y * ATLAS + x) * 4 + 3) as usize];

        // The space glyph is blank, 'A' is not, and the white texel is opaque.
        let (ax, ay) = glyph_origin(glyph_index('A'));
        let ink: u32 = (0..GLYPH)
            .flat_map(|y| (0..GLYPH).map(move |x| (x, y)))
            .map(|(x, y)| u32::from(alpha_at(ax + x, ay + y) > 0))
            .sum();
        assert!(ink > 8, "'A' should have ink, got {ink} lit pixels");

        let (sx, sy) = glyph_origin(glyph_index(' '));
        assert!((0..GLYPH).all(|y| (0..GLYPH).all(|x| alpha_at(sx + x, sy + y) == 0)));
        assert_eq!(alpha_at(WHITE_TEXEL.0, WHITE_TEXEL.1), 255);
    }
}
