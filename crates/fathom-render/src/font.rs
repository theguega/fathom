//! A monospace bitmap font, baked into the binary.
//!
//! No shaping stack, no runtime font loading, no dependency. Text *is* sprites,
//! exactly as it was on hardware that had no other option: `draw_text_at`
//! emits one quad per glyph into the same arena and the same pipeline as
//! `draw_texture`.
//!
//! Coverage is ASCII plus Latin-1. Anything outside that renders as `?`. For a
//! debugger that reads English instructions and numeric readouts that is the
//! right trade; CJK and Arabic want a real shaper, which belongs behind a
//! feature, not in the default dependency tree.

/// Width and height of one glyph cell, in atlas pixels.
pub(crate) const GLYPH: u32 = 8;
/// Glyph cells per atlas row.
const COLS: u32 = 16;
/// Square atlas edge, in pixels: 16x12 glyph cells plus a spare row.
pub(crate) const ATLAS: u32 = 128;
/// Where the solid-white texel used by untextured primitives lives.
const WHITE_TEXEL: (u32, u32) = (0, ATLAS - 4);

